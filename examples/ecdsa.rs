/// Print `got` and report whether it matches `expected`.
fn check(console_writer: &mut impl Write, name: &str, got: &[u8], expected: &[u8]) {
    let _ = write!(console_writer, "{name}: ");
    for byte in got {
        let _ = write!(console_writer, "{byte:02x}");
    }
    let _ = writeln!(console_writer);
    if got == expected {
        let _ = writeln!(console_writer, "{name} verification successful!");
    } else {
        let _ = writeln!(console_writer, "{name} verification failed!");
    }
}

fn main() {
    if let Err(e) = Ecdsa::exists() {
        writeln!(Console::writer(), "ECDSA DRIVER ERROR: {e:?}").unwrap();
        return;
    }
    let mut console_writer = Console::writer();
    let _ = writeln!(console_writer, "---------------Ecdsa Test---------------");

    if let Err(e) = Ecdsa::set_private_key_sync(&PRIVATE_KEY) {
        let _ = writeln!(console_writer, "Error while setting private key {e:?}");
        return;
    }

    let mut public_key: [u8; 64] = [0; 64];
    match Ecdsa::get_public_key_sync(&mut public_key) {
        Ok(()) => check(
            &mut console_writer,
            "Public key",
            &public_key,
            &EXPECTED_PUBLIC_KEY,
        ),
        Err(e) => {
            let _ = writeln!(console_writer, "Error while getting public key {e:?}");
        }
    }

    let mut signature: [u8; 64] = [0; 64];
    match Ecdsa::compute_sync(&HASH_TO_SIGN, &mut signature) {
        Ok(()) => check(
            &mut console_writer,
            "Signature",
            &signature,
            &EXPECTED_SIGNATURE,
        ),
        Err(e) => {
            let _ = writeln!(console_writer, "Error while computing signature {e:?}");
        }
    }
}
